"""Bundle the reviewed UI dictionaries without a runtime dependency or remote service."""
import json
from pathlib import Path

STATIC = Path(__file__).resolve().parent / "static"

def build_i18n():
    data = {name: json.loads((STATIC / "locales" / filename).read_text(encoding="utf-8"))
            for name, filename in (("ui", "ui.en.json"), ("fragments", "fragments.en.json"))}
    (STATIC / "i18n-data.js").write_text("// Generated by build_i18n.py.\nwindow.GuideTranslations = " +
        json.dumps(data, ensure_ascii=False, separators=(",", ":")) + ";\n", encoding="utf-8")

if __name__ == "__main__":
    build_i18n()
